public class Literals {
    public static void main(String[] args) {
        System.out.println("Literals");

        byte a = 127;
        short b = 4444;
        int c = 555555555;
        long d = 55555555555555555L;
        float e = 0.333f;
        double f = 5.555555555555;
        char ch = 'A';
        boolean g = true;
        String str = "Avi";

        System.out.println(d);
        System.out.println(str);
        System.out.println(f);
    }
}
